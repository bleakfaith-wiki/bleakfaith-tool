import os

import structlog

from bleakfaith_tool.game.items import Item, Items
from bleakfaith_tool.game.loot_table import LootTable

LOG = structlog.get_logger()


def append_preamble(lines: list[str]) -> None:
    lines.append("-- THIS FILE IS AUTOMATICALLY GENERATED")
    lines.append("-- DO NOT EDIT IT MANUALLY")


def preamble() -> list[str]:
    lines = []
    append_preamble(lines)
    return lines


def append_ids(lines: list[str], item: Item) -> None:
    lines.append(f"    id = {item.id},")
    lines.append(f"    guid = {item.guid},")


def start_item(lines: list[str], item: Item) -> None:
    lines.append(f"p.byGuid[{item.guid}] = {{")
    append_ids(lines, item)


def end_item(lines: list[str], item: Item) -> None:
    lines.append("}")
    lines.append(f"p.byId[{item.id}] = p.byGuid[{item.guid}]")


def render(lines: list[str]) -> str:
    return "\n".join(lines)


def gen_items(items: Items):
    lines = preamble()
    lines.append("local p = {")
    lines.append("    byGuid = {},")
    lines.append("    byId = {},")
    lines.append("    byName = {},")
    lines.append("}")

    for item in items.by_id_base.values():
        start_item(lines, item)
        lines.append(f'    name = "{item.name}",')
        if len(item.types) > 0:
            assert len(item.types) == 1, (
                f"Item {item.name} (GUID:{item.guid}) has multiple types: {item.types}"
            )
            lines.append(f'    type = "{item.types[0].value}",')
        # lines.append("    types = {")
        # for type in item.types:
        #     lines.append(f'        ["{type.value}"] = true,')
        # lines.append("    },")
        lines.append(f"    tier = {item.tier},")
        end_item(lines, item)
        lines.append(f'p.byName["{item.name}"] = p.byGuid[{item.guid}]')

    lines.append("return p")

    return render(lines)


def gen_weapons(items: Items):
    weapons = [i for i in items.by_id_base.values() if i.is_weapon]
    lines = preamble()
    lines.append("local p = {")
    lines.append("    byGuid = {},")
    lines.append("    byId = {},")
    lines.append("}")

    for weapon in weapons:
        wdat = weapon.weapon_data
        lines.append(f"-- {weapon.name}")
        start_item(lines, weapon)
        lines.append("    damage = {")
        lines.append(
            f"        [{weapon.tier}] = {{ min = {wdat.damage_min}, max = {wdat.damage_max} }},"
        )
        higher_tiers = [
            w for w in weapons if w.guid == weapon.guid and w.tier > weapon.tier
        ]
        higher_tiers.sort(key=lambda w: w.tier)
        for w in higher_tiers:
            lines.append(
                f"        [{w.tier}] = {{ min = {w.weapon_data.damage_min}, max = {w.weapon_data.damage_max} }},"
            )
        lines.append("    },")
        if wdat.type:
            lines.append(f'    type = "{wdat.type.value}",')
        if wdat.speed:
            lines.append(f'    speed = "{wdat.speed.value}",')
        if wdat.sharpness:
            lines.append(f'    sharpness = "{wdat.sharpness.value}",')
        if wdat.damage_type:
            lines.append(f'    damageType = "{wdat.damage_type.value}",')
        end_item(lines, weapon)

    lines.append("return p")

    return render(lines)


def gen_loot_tables(loot_tables: dict[int, LootTable], items: Items):
    lines = preamble()
    lines.append("local p = {}")

    for table in loot_tables.values():
        lines.append(f"-- {table.note}")
        lines.append(f"p[{table.id}] = {{")
        # lines.append(f'    note = "{table.note}",')
        lines.append("    items = {")
        for entry in sorted(table.entries, key=lambda e: e.item_id):
            item: Item = items.id_first(entry.item_id)  # ty: ignore[invalid-assignment]
            lines.append("        {")
            lines.append(f"            id = {entry.item_id}, -- {item.name}")
            lines.append(f"            rate = {entry.rate},")
            lines.append(f"            min = {entry.min},")
            lines.append(f"            max = {entry.max},")
            lines.append("        },")
        lines.append("    }")
        lines.append("}")

    lines.append("return p")

    return render(lines)


class LuaGenerator:
    def __init__(self, path: str) -> None:
        self.path = path
        os.makedirs(self.path, exist_ok=True)
        LOG.info("created lua output dir", path=self.path)

    def write_items(self, items: Items) -> None:
        lua_code = gen_items(items)
        self._write("items.lua", lua_code)

    def write_weapons(self, items: Items) -> None:
        lua_code = gen_weapons(items)
        self._write("weapons.lua", lua_code)

    def write_loot_tables(
        self, loot_tables: dict[int, LootTable], items: Items
    ) -> None:
        lua_code = gen_loot_tables(loot_tables, items)
        self._write("loot_tables.lua", lua_code)

    def _write(self, filename: str, content: str) -> None:
        path = os.path.join(self.path, filename)
        with open(path, "w") as f:
            f.write(content)
        LOG.info("wrote lua file", filename=filename, path=path)
