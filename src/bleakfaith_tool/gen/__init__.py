def append_preamble(lines: list[str]) -> None:
    lines.append("-- THIS FILE IS AUTOMATICALLY GENERATED")
    lines.append("-- DO NOT EDIT IT MANUALLY")


def preamble() -> list[str]:
    lines = []
    append_preamble(lines)
    return lines


def append_ids(lines: list[str], item: Item) -> None:
    lines.append(f"    id = {item.id},")
    lines.append(f"    guid = {item.guid},")


def start_item(lines: list[str], item: Item) -> None:
    lines.append(f"p.byGuid[{item.guid}] = {{")
    append_ids(lines, item)


def end_item(lines: list[str], item: Item) -> None:
    lines.append("}")
    lines.append(f"p.byId[{item.id}] = p.byGuid[{item.guid}]")


def format_bool(b: bool | None) -> str:
    if b is None:
        return "nil"
    return "true" if b else "false"


def format_num(v: float | None) -> str:
    if v is None:
        return "nil"
    return str(v)


def render(lines: list[str]) -> str:
    return "\n".join(lines)


def gen_items(items: Items) -> str:
    lines = preamble()
    lines.append("local p = {")
    lines.append("    byGuid = {},")
    lines.append("    byId = {},")
    lines.append("    byName = {},")
    lines.append("}")

    for item in items.by_id_base.values():
        start_item(lines, item)
        lines.append(f'    name = "{item.name}",')
        # Description is not used on wiki, for now at least
        # lines.append(f'    description = "{item.description}",')
        if len(item.types) > 0:
            assert len(item.types) == 1, (
                f"Item {item.name} (GUID:{item.guid}) has multiple types: {item.types}"
            )
            lines.append(f'    type = "{item.types[0].value}",')
        # lines.append("    types = {")
        # for type in item.types:
        #     lines.append(f'        ["{type.value}"] = true,')
        # lines.append("    },")
        lines.append(f"    tier = {item.tier}, -- Mk {item.tier - 1}")
        min_tier_item = min(items.id(item.id), key=lambda i: i.tier)  # ty: ignore[no-matching-overload]
        lines.append(
            f"    tierMin = {min_tier_item.tier}, -- Mk {min_tier_item.tier - 1}"
        )
        lines.append(f"    weight = {item.weight},")
        end_item(lines, item)
        lines.append(f'p.byName["{item.name}"] = p.byGuid[{item.guid}]')

    lines.append("return p")

    return render(lines)


def gen_weapons(
    items: Items, fragments: dict[int, Fragment], abilities: dict[str, Ability]
) -> str:
    weapons = [i for i in items.by_id_base.values() if i.is_weapon]
    lines = preamble()
    lines.append("local p = {")
    lines.append("    byGuid = {},")
    lines.append("    byId = {},")
    lines.append("}")

    for weapon in weapons:
        wdat = weapon.weapon_data
        lines.append(f"-- {weapon.name}")
        start_item(lines, weapon)
        lines.append("    damage = {")
        if wdat.damage_type:
            lines.append(f'        type = "{wdat.damage_type.value}",')
        lines.append(
            f"        [{weapon.tier}] = {{ min = {wdat.damage_min}, max = {wdat.damage_max} }}, -- Mk {weapon.tier - 1}"
        )
        higher_tiers = [
            w for w in items if w.guid == weapon.guid and w.tier > weapon.tier
        ]
        higher_tiers.sort(key=lambda w: w.tier)
        for w in higher_tiers:
            lines.append(
                f"        [{w.tier}] = {{ min = {w.weapon_data.damage_min}, max = {w.weapon_data.damage_max} }},"
            )
        lines.append("    },")
        if wdat.type:
            lines.append(f'    type = "{wdat.type.value}",')
        if wdat.speed:
            lines.append(f'    speed = "{wdat.speed.value}",')
        if wdat.sharpness:
            lines.append(f'    sharpness = "{wdat.sharpness.value}",')
        fdat = wdat.fragment_slot_data
        lines.append("    fragments = {")
        lines.append(f"        canBeEdited = {format_bool(fdat.can_be_edited)},")
        lines.append(f"        [{weapon.tier}] = {{ -- Mk {weapon.tier - 1}")
        lines.append(
            f"            numStatSlots = {fdat.number_of_available_stat_slots},"
        )
        lines.append("            statFragmentIds = {")
        for idx, id in enumerate(fdat.stat_fragment_ids):
            if id == 0:
                continue
            fragment = fragments.get(id)
            fragment_name: str | None = fragment.name if fragment else None
            lines.append(
                f"                [{idx + 1}] = {id}, -- {fragment_name if fragment_name else '<UNKNOWN FRAGMENT>'}"
            )
        lines.append("            },")
        lines.append(
            f"            numAbilitySlots = {fdat.number_of_available_ability_slots},"
        )
        lines.append("            abilityFragmentIds = {")
        for id in fdat.ability_fragment_ids:
            fragment = fragments.get(id)
            ability = (
                next(
                    (a for a in abilities.values() if a.fragment_id == fragment.id),
                    None,
                )
                if fragment
                else None
            )
            ability_name = ability.name if ability else None
            lines.append(
                f"                {id}, -- {f'{ability_name} ({"Passive" if ability.is_passive else "Active"})' if ability_name else '<UNKNOWN ABILITY>'}"  # ty: ignore[unresolved-attribute]
            )
        lines.append("            },")
        lines.append("        },")
        lines.append("    }")
        end_item(lines, weapon)

    lines.append("return p")

    return render(lines)


def gen_armor(items: Items) -> str:
    armors = [i for i in items.by_id_base.values() if i.is_armor]
    lines = preamble()
    lines.append("local p = {")
    lines.append("    byGuid = {},")
    lines.append("    byId = {},")
    lines.append("}")

    def print_defense(dat: ArmorData) -> None:
        lines.append(f"        [{dat.tier}] = {{ -- Mk {dat.tier - 1}")
        lines.append(f"            sharp = {dat.sharp},")
        lines.append(f"            sharpMultiplier = {dat.sharp_multiplier},")
        lines.append(f"            blunt = {dat.blunt},")
        lines.append(f"            bluntMultiplier = {dat.blunt_multiplier},")
        lines.append(f"            techno = {dat.techno},")
        lines.append(f"            technoMultiplier = {dat.techno_multiplier},")
        lines.append("        },")

    for armor in armors:
        adat = armor.armor_data
        lines.append(f"-- {armor.name}")
        start_item(lines, armor)
        lines.append("    defense = {")
        print_defense(adat)
        higher_tiers = [
            a for a in items if a.guid == armor.guid and a.tier > armor.tier
        ]
        higher_tiers.sort(key=lambda w: w.tier)
        for a in higher_tiers:
            print_defense(a.armor_data)
        lines.append("    },")
        if adat.weight:
            lines.append(f'    weight = "{adat.weight.value}",')
        if adat.slot:
            lines.append(f'    slot = "{adat.slot.value}",')
        end_item(lines, armor)

    lines.append("return p")

    return render(lines)


def gen_shields(items: Items) -> str:
    shields = [i for i in items.by_id_base.values() if i.is_shield]
    lines = preamble()
    lines.append("local p = {")
    lines.append("    byGuid = {},")
    lines.append("    byId = {},")
    lines.append("}")

    def print_defense(dat: ArmorData) -> None:
        lines.append(f"        [{dat.tier}] = {{ -- Mk {dat.tier - 1}")
        lines.append(f"            sharpMultiplier = {dat.sharp_multiplier},")
        lines.append(f"            bluntMultiplier = {dat.blunt_multiplier},")
        lines.append(f"            technoMultiplier = {dat.techno_multiplier},")
        lines.append("        },")

    for shield in shields:
        adat = shield.armor_data
        lines.append(f"-- {shield.name}")
        start_item(lines, shield)
        lines.append("    defense = {")
        print_defense(adat)
        higher_tiers = [
            s for s in items if s.guid == shield.guid and s.tier > shield.tier
        ]
        higher_tiers.sort(key=lambda s: s.tier)
        for s in higher_tiers:
            print_defense(s.armor_data)
        lines.append("    },")
        if shield.armor_data.weight:
            lines.append(f'    weight = "{shield.armor_data.weight.value}",')
        # lines.append(f'    slot = "{shield.armor_data.slot.value}",')
        end_item(lines, shield)

    lines.append("return p")

    return render(lines)


def gen_loot_tables(loot_tables: dict[int, LootTable], items: Items) -> str:
    lines = preamble()
    lines.append("local p = {")
    lines.append("    byId = {},")
    lines.append("}")

    for table in loot_tables.values():
        lines.append(f"-- {table.note}")
        lines.append(f"p.byId[{table.id}] = {{")
        # lines.append(f'    note = "{table.note}",')
        lines.append("    items = {")
        for entry in sorted(table.entries, key=lambda e: e.item_id):
            item: Item = items.id_first(entry.item_id)  # ty: ignore[invalid-assignment]
            lines.append("        {")
            lines.append(f"            id = {entry.item_id}, -- {item.name}")
            lines.append(f"            rate = {entry.rate},")
            lines.append(f"            min = {entry.min},")
            lines.append(f"            max = {entry.max},")
            lines.append("        },")
        lines.append("    }")
        lines.append("}")

    lines.append("return p")

    return render(lines)


def gen_abilities(abilities: dict[str, Ability]) -> str:
    lines = preamble()
    lines.append("local p = {")
    lines.append("    byKey = {},")
    lines.append("    byFragmentId = {},")
    lines.append("}")

    for ability in abilities.values():
        lines.append(f'p.byKey["{ability.key}"] = {{')
        lines.append(f'    key = "{ability.key}",')
        if ability.fragment_id:
            lines.append(f"    fragmentId = {ability.fragment_id},")
        lines.append(f"    isPassive = {format_bool(ability.is_passive)},")
        lines.append(f"    isGearPassive = {format_bool(ability.is_gear_passive)},")
        lines.append(f"    forceUpgrade = {format_bool(ability.force_upgrade)},")
        lines.append(f"    isClassActive = {format_bool(ability.is_class_active)},")
        if ability.unlocked_by:
            lines.append(f"    unlockedBy = {ability.unlocked_by},")
        lines.append(f'    element = "{ability.element}",')
        lines.append(f'    type = "{ability.type}",')
        lines.append(f'    target = "{ability.target}",')
        lines.append(f"    isWeaponBased = {format_bool(ability.is_weapon_based)},")
        assert len(ability.names) == 1
        name = ability.names["EAffinityType::VE_Unaffiliated"]
        lines.append(f'    name = "{name}",')
        lines.append(f"    baseDamage = {ability.base_damage},")
        lines.append(
            f"    isAffectedByCombos = {format_bool(ability.is_affected_by_combos)},"
        )
        lines.append("}")
        if ability.fragment_id:
            lines.append(
                f'p.byFragmentId[{ability.fragment_id}] = p.byKey["{ability.key}"]'
            )

    lines.append("return p")

    return render(lines)


def gen_fragments(fragments: dict[int, Fragment]) -> str:
    lines = preamble()
    lines.append("local p = {")
    lines.append("    byId = {},")
    lines.append("}")

    for fragment in fragments.values():
        lines.append(f"p.byId[{fragment.id}] = {{")
        lines.append(f"    id = {fragment.id},")
        lines.append(f"    isDebug = {format_bool(fragment.is_debug)},")
        lines.append(f'    name = "{fragment.name}",')
        lines.append(f'    type = "{fragment.type.value}",')
        lines.append(f"    tier = {fragment.tier},")
        lines.append(f"    isPassive = {format_bool(fragment.is_passive)},")
        if fragment.quest_id is not None:
            lines.append(f"    questId = {fragment.quest_id},")
        if fragment.ability_data:
            lines.append("    abilityData = {")
            lines.append("        acceptableWeapons = {")
            for weapon in fragment.ability_data.acceptable_weapons:
                lines.append(f'            "{weapon}",')
            lines.append("        },")
            lines.append("    },")
        elif fragment.stat_data:
            lines.append("    statData = {")
            lines.append("        armor = {")
            lines.append(
                f'            attribute = "{fragment.stat_data.armor.attribute}",'
            )
            lines.append(f"            amount = {fragment.stat_data.armor.amount},")
            lines.append("        },")
            lines.append("        weapon = {")
            lines.append(
                f'            attribute = "{fragment.stat_data.weapon.attribute}",'
            )
            lines.append(f"            amount = {fragment.stat_data.weapon.amount},")
            lines.append("        },")
            lines.append("    },")
        lines.append("}")

    lines.append("return p")

    return render(lines)


def gen_recipes(recipes: list[Recipe], items: Items) -> str:
    lines = preamble()
    lines.append("local p = {")
    lines.append("    byKey = {},")
    lines.append("}")

    for recipe in recipes:
        result_item: Item = items.id_first(recipe.item_id)  # ty: ignore[invalid-assignment]
        lines.append(f'p.byKey["{recipe.key}"] = {{')
        lines.append(f'    name = "{recipe.name}",')
        lines.append(f'    type = "{recipe.type}",')
        lines.append("    result = {")
        lines.append(f"        id = {recipe.item_id}, -- {result_item.name}")
        lines.append(f"        quantity = {recipe.per_craft},")
        lines.append("    },")
        lines.append("    ingredients = {")
        for id, quantity in recipe.materials.items():
            item: Item = items.id_first(id)  # ty: ignore[invalid-assignment]
            lines.append(f"        [{id}] = {quantity}, -- {item.name}")
        lines.append("    },")
        if recipe.needed_item:
            quest_id = recipe.needed_item
            lines.append("    needed = {")
            lines.append(f"        questId = {quest_id},")
            lines.append("        items = {")
            quest_items = items.quest_id(quest_id)
            for item in quest_items:
                lines.append(f"            {item.id}, -- {item.name}")
            lines.append("        },")
            lines.append("    },")
        else:
            lines.append("    needed = nil,")
        lines.append("    craft = {")
        for craft in recipe.craft:
            lines.append(f'        "{craft}",')
        lines.append("    },")
        if len(recipe.unlock) == 0:
            lines.append("    unlock = nil,")
        else:
            lines.append("    unlock = {")
            for unlock in recipe.unlock:
                lines.append(f'        "{unlock}",')
            lines.append("    },")
        lines.append("}")

    lines.append("return p")

    return render(lines)


def gen_npcs(npcs: list[Npc], items: Items, loot_tables: dict[int, LootTable]) -> str:
    lines = preamble()
    lines.append("local p = {")
    lines.append("    byId = {},")
    lines.append("}")

    for npc in npcs:
        id = npc.id.removesuffix("_C")
        lines.append(f'p["{id}"] = {{')
        lines.append(f"    isBoss = {format_bool(npc.is_boss)},")
        lines.append(f"    isUndamageable = {format_bool(npc.is_undamageable)},")
        lines.append(f"    faithfulStacks = {format_num(npc.faithful_stacks)},")
        lines.append(
            f"    maxPerfectBlockCounter = {format_num(npc.max_perfect_block_counter)},"
        )
        lines.append(
            f"    perfectBlockResetTimer = {format_num(npc.perfect_block_reset_timer)},"
        )
        lines.append("    attributes = {")
        if npc.attributes:
            lines.append(f"        strength = {format_num(npc.attributes.strength)},")
            lines.append(f"        agility = {format_num(npc.attributes.agility)},")
            lines.append(
                f"        constitution = {format_num(npc.attributes.constitution)},"
            )
            lines.append(
                f"        intelligence = {format_num(npc.attributes.intelligence)},"
            )
        lines.append("    },")
        lines.append("    capabilities = {")
        for cap in npc.capabilities:
            lines.append("        {")
            lines.append(f'            key = "{cap.key}",')
            lines.append(f"            current = {cap.current},")
            lines.append(f"            softCap = {cap.soft_cap},")
            lines.append(f"            hardCap = {cap.hard_cap},")
            lines.append("        },")
        lines.append("    },")
        lines.append("    experience = {")
        for threshold, exp in sorted(npc.experience.items()):
            lines.append(f"        [{threshold}] = {exp},")
        lines.append("    },")
        lines.append("    lootTables = {")
        for table_id in npc.loot_tables:
            lt = loot_tables.get(table_id)
            lines.append(
                f"        {table_id}, -- {lt.note if lt else f'<UNKNOWN LOOT TABLE {table_id}>'}"
            )
        lines.append("    },")
        lines.append("    extraLoot = {")
        for item_id in npc.extra_loot:
            item = items.by_id_base[item_id]
            lines.append(f"        {item_id}, -- {item.name}")
        lines.append("    },")
        lines.append("    equippedItems = {")
        for item_id in npc.equipped_items:
            item = items.by_id_base.get(item_id)
            lines.append(
                f"        {item_id}, -- {item.name if item else f'<UNKNOWN ITEM {item_id}>'}"
            )
        lines.append("    },")
        lines.append("}")

    lines.append("return p")

    return render(lines)


class LuaGenerator:
    def __init__(self, path: str) -> None:
        self.path = path
        os.makedirs(self.path, exist_ok=True)
        LOG.info("created lua output dir", path=self.path)

    def write_items(self, items: Items) -> None:
        lua_code = gen_items(items)
        self._write("items.lua", lua_code)

    def write_weapons(
        self,
        items: Items,
        fragments: dict[int, Fragment],
        abilities: dict[str, Ability],
    ) -> None:
        lua_code = gen_weapons(items, fragments, abilities)
        self._write("weapons.lua", lua_code)

    def write_armor(self, items: Items) -> None:
        lua_code = gen_armor(items)
        self._write("armor.lua", lua_code)

    def write_shields(self, items: Items) -> None:
        lua_code = gen_shields(items)
        self._write("shields.lua", lua_code)

    def write_loot_tables(
        self, loot_tables: dict[int, LootTable], items: Items
    ) -> None:
        lua_code = gen_loot_tables(loot_tables, items)
        self._write("loot_tables.lua", lua_code)

    def write_abilities(self, abilities: dict[str, Ability]) -> None:
        lua_code = gen_abilities(abilities)
        self._write("abilities.lua", lua_code)

    def write_fragments(self, fragments: dict[int, Fragment]) -> None:
        lua_code = gen_fragments(fragments)
        self._write("fragments.lua", lua_code)

    def write_recipes(self, recipes: list[Recipe], items: Items) -> None:
        lua_code = gen_recipes(recipes, items)
        self._write("recipes.lua", lua_code)

    def write_npcs(
        self, npcs: list[Npc], items: Items, loot_tables: dict[int, LootTable]
    ) -> None:
        lua_code = gen_npcs(npcs, items, loot_tables)
        self._write("npcs.lua", lua_code)

    def _write(self, filename: str, content: str) -> None:
        path = os.path.join(self.path, filename)
        with open(path, "w") as f:
            f.write(content)
        LOG.info("wrote lua file", filename=filename, path=path)
